/* HF observations are provider text, separate from author abstracts and citations. */
(function(root){
  function state(value,now=Date.now()) {
    const stamp=Date.parse(value?.fetched_at||'');
    const submitted=Date.parse(value?.submitted_on_daily_at||'');
    const recent=Number.isFinite(submitted)&&now>=submitted&&now-submitted<=30*86400000;
    const ttl=value?.status==='not_found'?7:recent?1:7;
    const available=Number.isFinite(stamp)&&stamp<=now&&!['unknown','ambiguous','not_found'].includes(value?.status);
    return {available,stale:available&&now-stamp>=ttl*86400000,status:value?.status||'unobserved'};
  }
  function safeLink(value) {
    try {const url=new URL(value);return url.protocol==='https:'&&!url.username&&!url.password?url.href:null;} catch {return null;}
  }
  function render(container,value,now=Date.now()) {
    container.replaceChildren();
    const element=(tag,text,cls='')=>{const el=document.createElement(tag);el.textContent=text;el.className=cls;return el;};
    const paragraph=text=>container.appendChild(element('p',text,'text-sm whitespace-pre-line break-words'));
    const link=(text,url)=>{const href=safeLink(url);if(!href)return;const el=element('a',text,'underline mr-3 break-words');el.href=href;el.target='_blank';el.rel='noopener noreferrer';container.appendChild(el);};
    container.classList.add('space-y-2');
    container.appendChild(element('h2','Hugging Face community','font-semibold'));
    const current=state(value,now);
    if(current.status==='unobserved'){paragraph('No Hugging Face observation recorded.');return;}
    if(current.status==='not_found'){paragraph(`No Hugging Face entry found in the recorded lookup (${value.last_attempt_at||'time unavailable'}).`);return;}
    if(!current.available){paragraph(`Hugging Face data unavailable. Latest attempt: ${current.status}.`);return;}
    paragraph(`Hugging Face observation: ${value.fetched_at}${current.stale?' · stale':''}${current.status!=='ok'?` · latest attempt: ${current.status}; showing retained values`:''}.`);
    const number=n=>Number.isInteger(n)&&n>=0?String(n):'unavailable';
    paragraph(`HF upvotes: ${number(value.upvotes)} · Repository stars reported by HF: ${number(value.stars)}`);
    link('Hugging Face paper',value.source_url);
    if(value.repository_evidence){link('Repository reported by HF (ownership unverified)',value.repository_evidence.url);}
    if(value.project_page_evidence){link('Project page reported by HF',value.project_page_evidence);}
    for(const [field,label] of [['provider_summary','Summary supplied by Hugging Face'],['provider_ai_summary','Summary generated by Hugging Face']]){
      const summary=value[field];
      if(summary?.provider==='huggingface'&&typeof summary.text==='string'){
        const details=element('details','');details.appendChild(element('summary',label,'cursor-pointer underline'));
        details.appendChild(element('p',summary.text,'text-sm whitespace-pre-line break-words'));container.appendChild(details);
      }
    }
    if(!Array.isArray(value.linked_spaces)){paragraph('Provider-linked Spaces: unavailable.');return;}
    const total=Number.isInteger(value.linked_spaces_total)?value.linked_spaces_total:null;
    if(!value.linked_spaces.length&&value.linked_spaces_complete===true&&total===0){paragraph('No provider-linked Spaces reported.');return;}
    paragraph(`Provider-linked Spaces: ${value.linked_spaces.length}${total!==null?` of ${total}`:''}${value.linked_spaces_complete===false?' (partial list)':''}. Links do not establish official ownership.`);
    for(const space of value.linked_spaces){link(space.id,space.url);}
  }
  const api={render,state,safeLink};
  if(typeof module!=='undefined')module.exports=api;
  root.HuggingFaceView=api;
})(typeof window!=='undefined'?window:globalThis);
